// 共享的敏感信息审计正则：桥接回复、MCP 发送、审批/提问文本等统一使用，避免两处维护不一致。
// 拦截本机路径/凭据特征；凭据关键词需带赋值关系才判定，避免误伤正常聊天。
//
// 结构（从外到内）：
//   ① 本机路径：Windows 绝对路径 / UNC / Linux 常见目录
//   ② `Bearer <长串>`（无冒号，HTTP 头最常见写法）
//   ③ 关键词 + 赋值：token/password/api_key/... 后跟 `:` `=` `：` 或中文「是/为」，再接值
//   ④ 中文赋值兜底：关键词 + 「是/为」+ 像凭据的长串
//   ⑤ 关键词 + 空格 + 像凭据的长串
//
// ⚠️ 历史加固记录（每次都是实测发现漏网，改动前先看这里）：
//   - 2026-10-10：接入 X 登录态时发现 ①漏 `ct0`（cookie 名不在词表）、②`Bearer <值>`完全没匹配、
//     ③`authorization: Bearer <含%的token>` 因旧字符类不认 `%` 只遮蔽了关键词本身；
//     另修好一条**本来就坏的** UNC 分支（`\\\\([^\\]+\\\\)+` 要求主机名两侧各两个反斜杠，
//     而真实 UNC 是 `\\server\share`，一直没生效）。
//   - 2026-10-11：接入 SauceNAO 时发现 **JSON 写法漏网**——`"apiKey": "d4f7…"`。
//     根因有两处：(a) 词表缺驼峰 `apikey`（`api[_-]?key` 不匹配 `apiKey`）；
//     (b) 关键词后紧跟的是**引号**再冒号，而分隔符判定 `\s*[:=：]` 只允许空白，
//     遇到 `"` 直接失败。修法：词表补 `apikey`，分隔符前后各允许一个可选引号，
//     值的字符类排除引号（避免把结尾引号也吞掉）。
//
// ⚠️ 改这个正则最容易犯的错：**删掉 `(?: ... | ... | ...)` 的外层分组**，
//   导致「中文是/为」「空格+值」这两条**脱离关键词**独立匹配，于是
//   「他 authorization 一下就行了」这种正常句子会被整句里的空格片段命中（实测踩过）。
//   改完务必跑 scripts/test-sensitive.mjs（里面同时有「必须遮蔽」与「必须放行」两类断言）。
export const SENSITIVE_RE = /((?<![A-Za-z0-9])[A-Za-z]:[\\/][^\s"'<>|]+|\\\\[^\s\\/]+\\[^\s\\/]+|(?<![A-Za-z0-9])(?:\/home\/|\/Users\/|\/etc\/|\/var\/)[^\s"'<>|]*|Bearer\s+[A-Za-z0-9%_.+/=-]{20,}|(?:token|ct0|cookie|session|密码|密钥|口令|password|passwd|secret|api[_-]?key|apikey|authorization|bearer|access[_-]?key|credential)(?:"?\s*[:=：]\s*"?(?:Bearer\s+)?[^\s，。；、"]{3,}|\s*(?:是|为)\s*(?:Bearer\s+)?[A-Za-z0-9%_.+/=-]{8,}|\s+[A-Za-z0-9_\-./%+=]{6,}))/i;

// 保留宿主日志前缀与返回值；输出位置由注入的 sink 决定，不自动脱敏。
export function createPluginLogger(id, sink = () => {}) {
  return msg => sink(`[plugin:${id}] ${msg}`);
}
