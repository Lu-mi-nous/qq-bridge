import { canonicalV2Key } from '../src/pipeline/social-state.js';
import { socialStateHarness, checks } from './helpers/pipeline-harness.mjs';
const { check, finish } = checks();
check('会话 key 规范化', canonicalV2Key('group:001') === 'group:1');
for (const key of ['group:0', '../private:1', 'other:1', 'private:9007199254740993']) check(`拒绝非法 key ${key}`, canonicalV2Key(key) === null);
const h = socialStateHarness(), s = h.store.getSocialV2State('group:1');
check('同会话复用状态', h.store.getSocialV2State('group:001') === s);
check('只创建一次计时器', h.calls.length === 2);
check('令牌登记', h.deps.KNOWN_AGENT_TOKENS.has(s.agentToken));
check('新会话初始未读为空', s.unread.length === 0 && s.wakeSeqAt === 0);
s.lastRequesterId = '42'; s.lastRequesterRole = 'owner'; s.ownerSpokeAt = Date.now();
s.answeredSeqs = [1, 2]; s.wakeSeqAt = 4; s.lastStickerAt = 100; s.recentStickers = ['a'];
s.stickerNudgeTimes = [10]; s.pendingWakeMessage = { seq: 4, plain: '未读快照' };
s.lastAutoAt = 123; s.autoAtTimes = [123]; s.pendingWakeReasons = [{ reason: 'atMention', seq: 4 }];
s.crawlTimes = [456]; s.stickerAddTimes = [789];
s.activeTopics = [{ text: '话题' }]; s.memberImpressions = { '42': { traits: ['同好'] } };
s.unread = [{ seq: 4, time: Date.now(), text: '你好' }];
h.store.saveSocialV2State();
check('保存只发生一次', h.writes.length === 1);
const raw = h.writes.at(-1), restored = socialStateHarness(raw); restored.store.loadSocialV2State();
const r = restored.deps.socialV2.conversations.get('group:1');
check('身份和管理员时间窗往返保持', r.lastRequesterId === '42' && r.lastRequesterRole === 'owner' && r.ownerSpokeAt === s.ownerSpokeAt);
check('已答序号与水位往返保持', r.answeredSeqs.join() === '1,2' && r.wakeSeqAt === 4);
check('自动@冷却重启后保持', r.lastAutoAt === 123 && r.autoAtTimes[0] === 123);
check('繁忙期间待唤醒原因重启后保持', r.pendingWakeReasons[0].reason === 'atMention');
check('爬取和收藏表情配额重启后保持', r.crawlTimes[0] === 456 && r.stickerAddTimes[0] === 789);
check('表情频率账往返保持', r.lastStickerAt === 100 && r.recentStickers[0] === 'a' && r.stickerNudgeTimes[0] === 10);
check('待唤醒快照/话题/印象保存', r.pendingWakeMessage.plain === '未读快照' && r.activeTopics.length === 1 && r.memberImpressions['42'].traits[0] === '同好');
check('加载仅在全部会话完成后保存', restored.writes.length === 1);
check('定时器未持久化', !('sleepTimer' in raw.conversations['group:1']));
const multi = structuredClone(raw); multi.conversations['private:2'] = structuredClone(raw.conversations['group:1']);
multi.conversations['group:1'].wakeConfig.triggers.speakerIds = [null, '12', {}, '12'];
multi.conversations['private:2'].wakeConfig.triggers.speakerIds = ['12'];
multi.conversations['group:1'].wakeConfig.confirmedBy = 'admin';
multi.conversations['private:2'].wakeConfig.confirmedBy = 'admin';
const m = socialStateHarness(multi); m.store.loadSocialV2State();
check('重复令牌在加载时重新分配', new Set([...m.deps.socialV2.conversations.values()].map(s => s.agentToken)).size === 2);
check('指定成员去脏去重', m.deps.socialV2.conversations.get('group:1').wakeConfig.triggers.speakerIds.join() === '12');
check('私聊不继承群成员唤醒名单', m.deps.socialV2.conversations.get('private:2').wakeConfig.triggers.speakerIds.length === 0);
check('有新消息且未观察时阻止沉睡', h.store.preSleepWaitBlockedV2({ lastIncomingAt: Date.now() }));
check('观察完成无新消息允许沉睡', !h.store.preSleepWaitBlockedV2({ lastIncomingAt: 1, preSleepWaitSatisfiedAt: 2 }));
check('明确告别允许沉睡', !h.store.preSleepWaitBlockedV2({ recentMessages: [{ text: '晚安', isSelf: false }] }));
finish();
